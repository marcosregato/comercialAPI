CREATE TABLE caixa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_caixa VARCHAR(50) NOT NULL UNIQUE,
    saldo_atual DECIMAL(19, 2) NOT NULL,
    CONSTRAINT chk_caixa_saldo_nao_negativo CHECK (saldo_atual >= 0)
);

CREATE TABLE sangria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caixa_id INTEGER NOT NULL,
    valor DECIMAL(19, 2) NOT NULL,
    saldo_antes DECIMAL(19, 2) NOT NULL,
    saldo_depois DECIMAL(19, 2) NOT NULL,
    motivo VARCHAR(50) NOT NULL,
    operador_nome VARCHAR(100) NOT NULL,
    supervisor_nome VARCHAR(100) NOT NULL,
    operador_assinatura VARCHAR(500) NOT NULL,
    supervisor_assinatura VARCHAR(500) NOT NULL,
    malote_lacrado BOOLEAN NOT NULL,
    detalhes_cedulas VARCHAR(1000),
    realizada_em TIMESTAMP NOT NULL,
    CONSTRAINT chk_sangria_valor_positivo CHECK (valor > 0),
    CONSTRAINT chk_sangria_saldos CHECK (saldo_antes >= valor AND saldo_depois = saldo_antes - valor),
    CONSTRAINT chk_sangria_motivo CHECK (motivo = 'EXCESSO_DE_CAIXA_SEGURANCA'),
    CONSTRAINT chk_sangria_malote_lacrado CHECK (malote_lacrado = TRUE),
    CONSTRAINT fk_sangria_caixa FOREIGN KEY (caixa_id) REFERENCES caixa (id)
);
