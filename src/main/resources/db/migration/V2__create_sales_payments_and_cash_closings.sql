CREATE TABLE venda (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor_total DECIMAL(19, 2) NOT NULL,
    realizada_em TIMESTAMP NOT NULL
);

CREATE TABLE pagamento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor DECIMAL(19, 2) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    realizado_em TIMESTAMP NOT NULL,
    venda_id INTEGER NOT NULL,
    CONSTRAINT fk_pagamento_venda
        FOREIGN KEY (venda_id) REFERENCES venda (id)
);

CREATE TABLE fechamento_caixa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total_vendas DECIMAL(19, 2) NOT NULL,
    total_descontos DECIMAL(19, 2) NOT NULL,
    total_lucro DECIMAL(19, 2) NOT NULL,
    total_caixa DECIMAL(19, 2) NOT NULL
);
